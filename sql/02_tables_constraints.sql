-- 1. Bang PHONG_BAN: Quan ly phong ban va han muc chi tieu noi bo hang thang
CREATE TABLE PHONG_BAN (
    MA_PB             VARCHAR2(20)   CONSTRAINT PK_PHONG_BAN PRIMARY KEY,
    TEN_PB            NVARCHAR2(100) NOT NULL,
    HAN_MUC_CHI_THANG NUMBER(18, 2)  DEFAULT 500000000 NOT NULL
        CONSTRAINT CHK_PB_HAN_MUC CHECK (HAN_MUC_CHI_THANG >= 0),
    TRANG_THAI        VARCHAR2(20)   DEFAULT 'HOAT_DONG' NOT NULL
        CONSTRAINT CHK_PB_TRANG_THAI CHECK (TRANG_THAI IN ('HOAT_DONG', 'NGUNG_HOAT_DONG')),
    NGAY_TAO          TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
);

-- 2. Bang NHAN_VIEN: Thong tin can bo nhan vien doanh nghiep
CREATE TABLE NHAN_VIEN (
    MA_NV         VARCHAR2(20)   CONSTRAINT PK_NHAN_VIEN PRIMARY KEY,
    HO_TEN        NVARCHAR2(120) NOT NULL,
    EMAIL         VARCHAR2(120)  NOT NULL CONSTRAINT UQ_NV_EMAIL UNIQUE,
    SO_DIEN_THOAI VARCHAR2(20)   NOT NULL,
    CHUC_VU       NVARCHAR2(80)  NOT NULL,
    MA_PB         VARCHAR2(20)   NOT NULL
        CONSTRAINT FK_NV_PHONG_BAN REFERENCES PHONG_BAN(MA_PB),
    TRANG_THAI    VARCHAR2(20)   DEFAULT 'DANG_LAM_VIEC' NOT NULL
        CONSTRAINT CHK_NV_TRANG_THAI CHECK (TRANG_THAI IN ('DANG_LAM_VIEC', 'NGHI_VIEC')),
    NGAY_VAO_LAM  DATE           DEFAULT SYSDATE NOT NULL
);

-- 3. Bang VI_DIEN_TU: Vi dien tu noi bo gan voi nhan vien / doi tac / he thong
CREATE TABLE VI_DIEN_TU (
    MA_VI           VARCHAR2(20)  CONSTRAINT PK_VI_DIEN_TU PRIMARY KEY,
    SO_TAI_KHOAN    VARCHAR2(30)  NOT NULL CONSTRAINT UQ_VI_STK UNIQUE,
    MA_NV           VARCHAR2(20)  NOT NULL
        CONSTRAINT FK_VI_NHAN_VIEN REFERENCES NHAN_VIEN(MA_NV),
    LOAI_VI         VARCHAR2(20)  DEFAULT 'NHAN_VIEN' NOT NULL
        CONSTRAINT CHK_VI_LOAI CHECK (LOAI_VI IN ('NHAN_VIEN', 'DOI_TAC', 'HE_THONG')),
    SO_DU           NUMBER(18, 2) DEFAULT 0 NOT NULL
        CONSTRAINT CHK_VI_SO_DU CHECK (SO_DU >= 0),
    SO_DU_KHA_DUNG  NUMBER(18, 2) DEFAULT 0 NOT NULL
        CONSTRAINT CHK_VI_KHA_DUNG CHECK (SO_DU_KHA_DUNG >= 0),
    HAN_MUC_NGAY    NUMBER(18, 2) DEFAULT 50000000 NOT NULL
        CONSTRAINT CHK_VI_HAN_MUC_NGAY CHECK (HAN_MUC_NGAY > 0),
    TRANG_THAI      VARCHAR2(20)  DEFAULT 'HOAT_DONG' NOT NULL
        CONSTRAINT CHK_VI_TRANG_THAI CHECK (TRANG_THAI IN ('HOAT_DONG', 'TAM_KHOA', 'DONG_VINH_VIEN')),
    VERSION_LOCK    NUMBER(10)    DEFAULT 0 NOT NULL,
    NGAY_MO         TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    NGAY_CAP_NHAT   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CHK_VI_KHA_DUNG_LE_DU CHECK (SO_DU_KHA_DUNG <= SO_DU),
    CONSTRAINT UQ_VI_NV_LOAI UNIQUE (MA_NV, LOAI_VI)
);

-- 4. Bang DOI_TAC_DICH_VU: Cac diem chap nhan thanh toan noi bo (Can tin, Bai xe, In an...)
CREATE TABLE DOI_TAC_DICH_VU (
    MA_DOI_TAC   VARCHAR2(20)   CONSTRAINT PK_DOI_TAC PRIMARY KEY,
    TEN_DOI_TAC  NVARCHAR2(120) NOT NULL,
    LOAI_DICH_VU VARCHAR2(40)   NOT NULL
        CONSTRAINT CHK_DT_LOAI CHECK (LOAI_DICH_VU IN ('CAN_TIN', 'BAI_XE', 'IN_AN', 'VAN_PHONG_PHAM', 'Y_TE', 'KHAC')),
    MA_VI_NHAN   VARCHAR2(20)   NOT NULL
        CONSTRAINT FK_DT_VI_NHAN REFERENCES VI_DIEN_TU(MA_VI),
    TRANG_THAI   VARCHAR2(20)   DEFAULT 'HOAT_DONG' NOT NULL
        CONSTRAINT CHK_DT_TRANG_THAI CHECK (TRANG_THAI IN ('HOAT_DONG', 'TAM_NGUNG')),
    NGAY_TAO     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
);

-- 5. Bang LOAI_GIAO_DICH: Danh muc nghiep vu va bieu phi giao dich
CREATE TABLE LOAI_GIAO_DICH (
    MA_LOAI_GD      VARCHAR2(30)   CONSTRAINT PK_LOAI_GD PRIMARY KEY,
    TEN_LOAI        NVARCHAR2(100) NOT NULL,
    PHI_CO_DINH     NUMBER(18, 2)  DEFAULT 0 NOT NULL
        CONSTRAINT CHK_LGD_PHI_CD CHECK (PHI_CO_DINH >= 0),
    TY_LE_PHI       NUMBER(6, 4)   DEFAULT 0 NOT NULL
        CONSTRAINT CHK_LGD_TY_LE CHECK (TY_LE_PHI >= 0 AND TY_LE_PHI <= 0.1),
    PHI_TOI_DA      NUMBER(18, 2)  DEFAULT 50000 NOT NULL
        CONSTRAINT CHK_LGD_PHI_MAX CHECK (PHI_TOI_DA >= 0),
    CO_TINH_HAN_MUC NUMBER(1)      DEFAULT 1 NOT NULL
        CONSTRAINT CHK_LGD_HAN_MUC CHECK (CO_TINH_HAN_MUC IN (0, 1)),
    MO_TA           NVARCHAR2(255)
);

-- 6. Bang GIAO_DICH: Luu vet toan bo giao dich nap, rut, chuyen tien, thanh toan, hoan tien
CREATE TABLE GIAO_DICH (
    MA_GD           NUMBER(18)     CONSTRAINT PK_GIAO_DICH PRIMARY KEY,
    MA_THAM_CHIEU   VARCHAR2(80)   NOT NULL CONSTRAINT UQ_GD_THAM_CHIEU UNIQUE,
    MA_VI_NGUON     VARCHAR2(20)
        CONSTRAINT FK_GD_VI_NGUON REFERENCES VI_DIEN_TU(MA_VI),
    MA_VI_DICH      VARCHAR2(20)
        CONSTRAINT FK_GD_VI_DICH REFERENCES VI_DIEN_TU(MA_VI),
    MA_LOAI_GD      VARCHAR2(30)   NOT NULL
        CONSTRAINT FK_GD_LOAI REFERENCES LOAI_GIAO_DICH(MA_LOAI_GD),
    MA_GD_GOC       NUMBER(18)
        CONSTRAINT FK_GD_GOC REFERENCES GIAO_DICH(MA_GD),
    SO_TIEN         NUMBER(18, 2)  NOT NULL
        CONSTRAINT CHK_GD_SO_TIEN CHECK (SO_TIEN > 0),
    PHI_GD          NUMBER(18, 2)  DEFAULT 0 NOT NULL
        CONSTRAINT CHK_GD_PHI CHECK (PHI_GD >= 0),
    TONG_TIEN       NUMBER(18, 2)  NOT NULL
        CONSTRAINT CHK_GD_TONG_TIEN CHECK (TONG_TIEN > 0),
    NOI_DUNG        NVARCHAR2(255),
    TRANG_THAI      VARCHAR2(20)   DEFAULT 'THANH_CONG' NOT NULL
        CONSTRAINT CHK_GD_TRANG_THAI CHECK (TRANG_THAI IN ('CHO_XU_LY', 'THANH_CONG', 'THAT_BAI', 'DA_HOAN_TIEN')),
    NGUOI_THUC_HIEN VARCHAR2(50)   DEFAULT 'SYSTEM' NOT NULL,
    NGAY_TAO        TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    NGAY_HOAN_TAT   TIMESTAMP
);

-- 7. Bang CHI_TIET_SO_CAI: So cai ke toan kep (Double-entry Ledger) dam bao can bang tai chinh
CREATE TABLE CHI_TIET_SO_CAI (
    MA_BUT_TOAN   NUMBER(18)     CONSTRAINT PK_SO_CAI PRIMARY KEY,
    MA_GD         NUMBER(18)     NOT NULL
        CONSTRAINT FK_SC_GIAO_DICH REFERENCES GIAO_DICH(MA_GD),
    MA_VI         VARCHAR2(20)   NOT NULL
        CONSTRAINT FK_SC_VI REFERENCES VI_DIEN_TU(MA_VI),
    LOAI_BUT_TOAN VARCHAR2(10)   NOT NULL
        CONSTRAINT CHK_SC_LOAI CHECK (LOAI_BUT_TOAN IN ('GHI_NO', 'GHI_CO')),
    SO_TIEN       NUMBER(18, 2)  NOT NULL
        CONSTRAINT CHK_SC_SO_TIEN CHECK (SO_TIEN > 0),
    SO_DU_TRUOC   NUMBER(18, 2)  NOT NULL
        CONSTRAINT CHK_SC_DU_TRUOC CHECK (SO_DU_TRUOC >= 0),
    SO_DU_SAU     NUMBER(18, 2)  NOT NULL
        CONSTRAINT CHK_SC_DU_SAU CHECK (SO_DU_SAU >= 0),
    MO_TA         NVARCHAR2(255),
    NGAY_GHI_SO   TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
);

-- 8. Bang NHAT_KY_LOI_GIAO_DICH: Ghi nhan ngoai le bang AUTONOMOUS_TRANSACTION ke ca khi ROLLBACK
CREATE TABLE NHAT_KY_LOI_GIAO_DICH (
    MA_LOG          NUMBER(18)      CONSTRAINT PK_LOG_LOI PRIMARY KEY,
    MA_THAM_CHIEU   VARCHAR2(80),
    TEN_MODULE      VARCHAR2(100)   NOT NULL,
    MA_LOI_ORACLE   NUMBER(10)      NOT NULL,
    MA_LOI_NGHIEP_VU VARCHAR2(50)   NOT NULL,
    THONG_DIEP_LOI  NVARCHAR2(500)  NOT NULL,
    DU_LIEU_DAU_VAO NVARCHAR2(1000),
    STACK_TRACE     VARCHAR2(2000),
    NGUOI_THUC_HIEN VARCHAR2(50)    DEFAULT 'SYSTEM' NOT NULL,
    THOI_GIAN_LOI   TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL
);

-- 9. Bang NHAT_KY_TRANG_THAI_VI: Audit log tu dong ghi boi Trigger khi trang thai vi thay doi
CREATE TABLE NHAT_KY_TRANG_THAI_VI (
    MA_LOG_TT       NUMBER(18)     CONSTRAINT PK_LOG_TT_VI PRIMARY KEY,
    MA_VI           VARCHAR2(20)   NOT NULL
        CONSTRAINT FK_LTT_VI REFERENCES VI_DIEN_TU(MA_VI),
    TRANG_THAI_CU   VARCHAR2(20),
    TRANG_THAI_MOI  VARCHAR2(20)   NOT NULL,
    LY_DO           NVARCHAR2(255),
    NGUOI_THAY_DOI  VARCHAR2(50)   DEFAULT 'SYSTEM' NOT NULL,
    THOI_GIAN       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
);

-- Chu thich bang (Metadata Documentation)
COMMENT ON TABLE PHONG_BAN IS 'Danh muc phong ban trong doanh nghiep';
COMMENT ON TABLE NHAN_VIEN IS 'Thong tin nhan vien su dung vi dien tu noi bo';
COMMENT ON TABLE VI_DIEN_TU IS 'Tai khoan vi dien tu noi bo cua nhan vien, doi tac va he thong';
COMMENT ON TABLE DOI_TAC_DICH_VU IS 'Cac don vi cung ung dich vu noi bo (can tin, bai xe, in an...)';
COMMENT ON TABLE LOAI_GIAO_DICH IS 'Danh muc loai giao dich va quy tac tinh phi';
COMMENT ON TABLE GIAO_DICH IS 'Bang giao dich chinh voi khoa chong trung lap MA_THAM_CHIEU';
COMMENT ON TABLE CHI_TIET_SO_CAI IS 'So cai ke toan kep ghi nhan bien dong so du tung vi';
COMMENT ON TABLE NHAT_KY_LOI_GIAO_DICH IS 'Bang luu vet ngoai le thong qua PRAGMA AUTONOMOUS_TRANSACTION';
COMMENT ON TABLE NHAT_KY_TRANG_THAI_VI IS 'Lich su khoa/mo khoa vi duoc ghi tu dong boi Trigger';

-- View tong hop thong tin vi va nhan vien cho ung dung va bao cao
CREATE OR REPLACE VIEW VW_TONG_HOP_VI_NHAN_VIEN AS
SELECT
    v.MA_VI,
    v.SO_TAI_KHOAN,
    v.LOAI_VI,
    nv.MA_NV,
    nv.HO_TEN,
    nv.EMAIL,
    nv.CHUC_VU,
    pb.MA_PB,
    pb.TEN_PB,
    v.SO_DU,
    v.SO_DU_KHA_DUNG,
    v.HAN_MUC_NGAY,
    v.TRANG_THAI,
    v.NGAY_MO,
    v.NGAY_CAP_NHAT
FROM VI_DIEN_TU v
JOIN NHAN_VIEN nv ON v.MA_NV = nv.MA_NV
JOIN PHONG_BAN pb ON nv.MA_PB = pb.MA_PB;
